import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { detectFramework, detectPackageManager, packageManagerCommands } from "../src/detect.js";
import { cleanup, cli, makeProject, NEXT_PKG } from "./helpers.js";

const dirs = [];

afterEach(async () => {
  await Promise.all(dirs.splice(0).map(cleanup));
});

async function tree(files) {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), "virastack-ai-detect-"));
  dirs.push(dir);
  for (const [file, content] of Object.entries(files)) {
    await fs.mkdir(path.dirname(path.join(dir, file)), { recursive: true });
    await fs.writeFile(path.join(dir, file), content);
  }
  return dir;
}

describe("commands per package manager", () => {
  const expected = {
    pnpm: ["pnpm install", "pnpm dev", "pnpm lint && pnpm typecheck", "pnpm test", "pnpm vitest run", "pnpm build", "pnpm dlx"],
    npm: ["npm install", "npm run dev", "npm run lint && npm run typecheck", "npm test", "npx vitest run", "npm run build", "npx"],
    yarn: ["yarn install", "yarn dev", "yarn lint && yarn typecheck", "yarn test", "yarn vitest run", "yarn build", "yarn dlx"],
    "yarn-classic": ["yarn install", "yarn dev", "yarn lint && yarn typecheck", "yarn test", "yarn vitest run", "yarn build", "npx"],
    bun: ["bun install", "bun run dev", "bun run lint && bun run typecheck", "bun run test", "bunx vitest run", "bun run build", "bunx"],
  };

  for (const [manager, [install, dev, validate, test, testFile, build, exec]] of Object.entries(expected)) {
    it(`gives ${manager} its own commands`, () => {
      expect(packageManagerCommands(manager)).toEqual({ install, dev, validate, test, testFile, build, exec });
    });
  }
});

describe("framework detection", () => {
  it("prefers the template recorded in package.json", () => {
    const pkg = { virastack: { template: "tanstack" }, dependencies: { next: "16.0.0" } };
    expect(detectFramework(pkg)).toBe("tanstack");
  });

  it("does not treat TanStack Router alone as TanStack Start", () => {
    expect(detectFramework({ dependencies: { "@tanstack/react-router": "1.0.0" } })).toBeNull();
  });

  it("detects TanStack Start, which also depends on the router", () => {
    const dependencies = { "@tanstack/react-router": "1.0.0", "@tanstack/react-start": "1.0.0" };
    expect(detectFramework({ dependencies })).toBe("tanstack");
  });

  it("asks for --framework on a router-only project and installs nothing", async () => {
    const dir = await makeProject({ dependencies: { "@tanstack/react-router": "1.0.0" } });
    dirs.push(dir);
    const { code, err } = await cli(dir, ["init", "--yes"]);
    expect(code).toBe(1);
    expect(err).toContain("--framework");
    await expect(fs.access(path.join(dir, "AGENTS.md"))).rejects.toThrow();
  });
});

describe("Yarn versions", () => {
  const CLASSIC_LOCK = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n";
  const BERRY_LOCK = '# This file is generated by running "yarn install"\n\n__metadata:\n  version: 8\n';

  it("uses npx with a Yarn 1 lockfile, which has no dlx", async () => {
    const dir = await tree({ "yarn.lock": CLASSIC_LOCK });
    expect(packageManagerCommands(await detectPackageManager(dir, {})).exec).toBe("npx");
  });

  it("uses yarn dlx with a modern lockfile", async () => {
    const dir = await tree({ "yarn.lock": BERRY_LOCK });
    expect(packageManagerCommands(await detectPackageManager(dir, {})).exec).toBe("yarn dlx");
  });

  it("reads the version from the packageManager field", async () => {
    const dir = await tree({});
    const classic = await detectPackageManager(dir, { packageManager: "yarn@1.22.22" });
    const modern = await detectPackageManager(dir, { packageManager: "yarn@4.5.0" });
    expect(packageManagerCommands(classic).exec).toBe("npx");
    expect(packageManagerCommands(modern).exec).toBe("yarn dlx");
  });

  it("keeps yarn for every other command", async () => {
    const dir = await tree({ "yarn.lock": CLASSIC_LOCK });
    expect(packageManagerCommands(await detectPackageManager(dir, {})).test).toBe("yarn test");
  });

  it("writes npx into the installed rule", async () => {
    const dir = await makeProject(NEXT_PKG, { "yarn.lock": CLASSIC_LOCK });
    dirs.push(dir);
    await cli(dir, ["init", "--agent", "claude", "--yes"]);
    const rule = await fs.readFile(path.join(dir, ".claude/rules/virastack/ui.md"), "utf8");
    expect(rule).toContain("npx shadcn@latest add");
  });
});

describe("package manager priority", () => {
  it("prefers the packageManager field over a lockfile", async () => {
    const dir = await tree({ "package-lock.json": "" });
    expect(await detectPackageManager(dir, { packageManager: "pnpm@10.0.0" })).toBe("pnpm");
  });
});

describe("lockfile in a monorepo", () => {
  it("finds the lockfile at the repository root", async () => {
    const root = await tree({ ".git/HEAD": "ref\n", "pnpm-lock.yaml": "", "apps/web/package.json": "{}" });
    expect(await detectPackageManager(path.join(root, "apps/web"), {})).toBe("pnpm");
  });

  it("prefers the closest lockfile", async () => {
    const root = await tree({ ".git/HEAD": "ref\n", "pnpm-lock.yaml": "", "apps/web/bun.lock": "" });
    expect(await detectPackageManager(path.join(root, "apps/web"), {})).toBe("bun");
  });

  it("does not look above the repository root", async () => {
    const root = await tree({ "pnpm-lock.yaml": "", "repo/.git/HEAD": "ref\n", "repo/apps/web/package.json": "{}" });
    expect(await detectPackageManager(path.join(root, "repo/apps/web"), {})).toBe("npm");
  });

  it("does not look at parent folders outside a repository", async () => {
    const root = await tree({ "pnpm-lock.yaml": "", "apps/web/package.json": "{}" });
    expect(await detectPackageManager(path.join(root, "apps/web"), {})).toBe("npm");
  });
});
